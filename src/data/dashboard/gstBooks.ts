function L(id: string, label: string, amount?: string): TSideRow {
  return { id, label, amount };
}

function closingFrom(led: TAccount): string {
  const cr = led.right.find((r) => /Balance [Cc]\/d/i.test(r.label))?.amount;
  const dr = led.left.find((r) => /Balance [Cc]\/d/i.test(r.label))?.amount;
  if (cr) return `${cr} Cr`;
  if (dr) return `${dr} Dr`;
  return led.leftTotal;
}

function withIndex(
  ledgers: TAccount[],
  sources: Record<string, string>,
): { ledgers: TAccount[]; ledgerIndex: LedgerIndexEntry[] } {
  return {
    ledgers,
    ledgerIndex: ledgers.map((led, i) => ({
      no: i + 1,
      ledgerId: led.id,
      name: led.title,
      source: sources[led.id] ?? 'GST',
      closingBalance: closingFrom(led),
    })),
  };
}

/** Build balanced totals from numeric parts — avoid fragile string math. */
function bal(n: number): string {
  return n.toLocaleString('en-IN');
}

function outputTaxLedger(
  id: string,
  entityId: string,
  entityLabel: string,
  title: string,
  opening: number,
  output: number,
  setOff: number,
): TAccount {
  const closing = opening + output - setOff;
  return {
    id,
    entityId,
    entityLabel,
    title,
    subtitle: 'Duties & Taxes · Output GST',
    leftHeader: 'Date / Particulars',
    rightHeader: 'Date / Particulars',
    left: [
      L('l1', 'To Electronic Credit / Cash Ledger (set-off)', bal(setOff)),
      L('l2', 'To Balance C/d', bal(closing)),
    ],
    right: [
      L('r1', 'By Balance B/d', bal(opening)),
      L('r2', 'By Output tax on outward supplies', bal(output)),
    ],
    leftTotal: bal(opening + output),
    rightTotal: bal(opening + output),
  };
}

function inputTaxLedger(
  id: string,
  entityId: string,
  entityLabel: string,
  title: string,
  opening: number,
  input: number,
  utilised: number,
): TAccount {
  const closing = opening + input - utilised;
  return {
    id,
    entityId,
    entityLabel,
    title,
    subtitle: 'Duties & Taxes · Input GST',
    leftHeader: 'Date / Particulars',
    rightHeader: 'Date / Particulars',
    left: [
      L('l1', 'To Balance B/d', bal(opening)),
      L('l2', 'To Input tax on inward supplies / 2B', bal(input)),
    ],
    right: [
      L('r1', 'By Utilised / reversed', bal(utilised)),
      L('r2', 'By Balance C/d', bal(closing)),
    ],
    leftTotal: bal(opening + input),
    rightTotal: bal(opening + input),
  };
}

function cashLedger(
  id: string,
  entityId: string,
  entityLabel: string,
  opening: number,
  deposits: number,
  utilised: number,
): TAccount {
  const closing = opening + deposits - utilised;
  return {
    id,
    entityId,
    entityLabel,
    title: 'Electronic Cash Ledger',
    subtitle: 'GSTN portal ledger',
    leftHeader: 'Date / Particulars',
    rightHeader: 'Date / Particulars',
    left: [
      L('l1', 'To Balance B/d', bal(opening)),
      L('l2', 'To Cash / PMT-06 deposits', bal(deposits)),
    ],
    right: [
      L('r1', 'By Tax / interest / fee paid', bal(utilised)),
      L('r2', 'By Balance C/d', bal(closing)),
    ],
    leftTotal: bal(opening + deposits),
    rightTotal: bal(opening + deposits),
  };
}

function creditLedger(
  id: string,
  entityId: string,
  entityLabel: string,
  opening: number,
  credited: number,
  utilised: number,
): TAccount {
  const closing = opening + credited - utilised;
  return {
    id,
    entityId,
    entityLabel,
    title: 'Electronic Credit Ledger',
    subtitle: 'GSTN portal ledger · ITC',
    leftHeader: 'Date / Particulars',
    rightHeader: 'Date / Particulars',
    left: [
      L('l1', 'To Balance B/d', bal(opening)),
      L('l2', 'To ITC credited (GSTR-2B / 3B)', bal(credited)),
    ],
    right: [
      L('r1', 'By ITC utilised against liability', bal(utilised)),
      L('r2', 'By Balance C/d', bal(closing)),
    ],
    leftTotal: bal(opening + credited),
    rightTotal: bal(opening + credited),
  };
}

