export function getClientPropertyAssets(clientId: string = CURRENT_CLIENT_ID): PropertyAsset[] {
  return PROPERTY_ASSETS.filter((p) => p.clientId === clientId);
}

export function getClientStockHoldings(clientId: string = CURRENT_CLIENT_ID): StockHolding[] {
  return STOCK_HOLDINGS.filter((h) => h.clientId === clientId);
}

export function getClientStockLedger(clientId: string = CURRENT_CLIENT_ID): StockLedgerEntry[] {
  return STOCK_LEDGER.filter((e) => e.clientId === clientId);
}

export function getClientInvestmentCompliances(
  clientId: string = CURRENT_CLIENT_ID,
): InvestmentComplianceItem[] {
  return INVESTMENT_COMPLIANCES.filter((c) => c.clientId === clientId);
}

export function formatInr(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatInrPrecise(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 2,
  }).format(amount);
}
